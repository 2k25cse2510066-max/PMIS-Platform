export function normalizeInternship(item) {
  const matchVal = typeof item.match === 'number' ? item.match : (item.match?.overall || 75);
  const skillsList = item.skills || item.required_skills || [];
  const matched = item.match?.matchedSkills || skillsList.slice(0, 2);
  const missing = item.missingSkills || item.match?.missingSkills || [];
  const reasons = item.reason
    ? [item.reason]
    : (item.match?.reasons || ['Strong match based on your technical skills & experience.']);

  return {
    ...item,
    company_name: item.company_name || item.company || 'TechNova Solutions',
    company_verified: item.company_verified !== undefined ? item.company_verified : (item.verified ?? true),
    required_skills: skillsList,
    location: item.location || 'Remote',
    stipend: item.stipend || '₹12,000/month',
    type: item.type || item.mode || 'Remote',
    seats: item.seats || item.seatsLeft || 3,
    closesIn: item.closesIn || '3 days',
    missingSkills: missing,
    reason: item.reason || reasons[0],
    match: {
      overall: matchVal,
      matchedSkills: matched,
      missingSkills: missing,
      reasons: reasons,
    }
  };
}

